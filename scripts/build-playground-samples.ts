/**
 * pkinative — playground samples (`npm run docs:playground-samples`)
 * ==================================================================
 * Writes `docs/playgrounds/samples.js`, the certificates the playgrounds offer
 * in their pickers, from the committed DER test fixtures. The engine itself is
 * not here: the playgrounds import the published package from a CDN, pinned
 * to this site's version (`docs/playgrounds/load-engine.js`, held by the
 * `cdn-pin` rule; ADR 0023). What stays first-party is the data a reader
 * picks, and that data is the suite's own — there is no second corpus to keep
 * honest.
 *
 * `--check` re-derives the file and compares it byte for byte (gate step
 * `docs:playground-samples-fresh`), so a fixture changed without a regeneration fails
 * the gate rather than the playground.
 *
 * @module scripts/build-playground-samples
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const SAMPLES_TARGET = 'docs/playgrounds/samples.js';

/**
 * The certificates the playground offers, and the one-line description each
 * carries in the picker. They are the committed test fixtures — foreign
 * provenance recorded in tests/fixtures/PROVENANCE.md — so the playground
 * demonstrates the library on exactly the bytes the suite is held to, and
 * there is no second corpus to keep honest.
 */
export const SAMPLES: ReadonlyArray<readonly [id: string, fixture: string, label: string]> = [
    ['isrg-root-x1', 'isrg-root-x1', 'ISRG Root X1 — a self-signed RSA-4096 root'],
    ['isrg-root-x2', 'isrg-root-x2', 'ISRG Root X2 — the same root, on P-384'],
    ['lets-encrypt-r12', 'lets-encrypt-r12', "Let's Encrypt R12 — an RSA intermediate"],
    ['lets-encrypt-e7', 'lets-encrypt-e7', "Let's Encrypt E7 — an ECDSA intermediate"],
    ['letsencrypt-org-leaf', 'letsencrypt-org-leaf', 'letsencrypt.org — an end-entity with ten SANs'],
    ['rfc8410-x25519', 'rfc8410-x25519', 'RFC 8410 §10.2 — an X25519 certificate'],
];

/** `docs/playgrounds/samples.js`, built from the committed DER fixtures. */
export function renderSamples(der: (fixture: string) => Buffer): string {
    const blocks = SAMPLES.map(([id, fixture, label]) => {
        const lines = (der(fixture).toString('base64').match(/.{1,64}/g) ?? []);
        const pem = ['-----BEGIN CERTIFICATE-----', ...lines, '-----END CERTIFICATE-----']
            .map((line) => `            '${line}',`).join('\n');
        return `    {\n        id: '${id}',\n        label: ${JSON.stringify(label).replace(/'/g, "\\u0027")},\n        pem: [\n${pem}\n        ].join('\\n') + '\\n',\n    },`;
    }).join('\n');
    return `/* ═══════════════════════════════════════════════════════════════
   pkinative.dev — playground samples
   The ${String(SAMPLES.length)} certificates the test suite uses as known-answer fixtures,
   with their provenance recorded in tests/fixtures/PROVENANCE.md. The
   playground therefore demonstrates the library on exactly the bytes the
   suite is held to.
   Generated by scripts/build-playground-samples.ts — never hand-edited.
   ═══════════════════════════════════════════════════════════════ */

export const SAMPLES = [
${blocks}
];
`;
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
    const root = join(dirname(fileURLToPath(import.meta.url)), '..');
    const committed = existsSync(join(root, SAMPLES_TARGET)) ? readFileSync(join(root, SAMPLES_TARGET), 'utf8') : null;
    const samples = renderSamples((fixture) => readFileSync(join(root, `tests/fixtures/certs/${fixture}.der`)));
    if (process.argv.includes('--check')) {
        if (committed === samples) {
            console.error(`build-playground-samples: ${SAMPLES_TARGET} matches the ${String(SAMPLES.length)} fixtures`);
            process.exit(0);
        }
        console.error(`build-playground-samples: ${SAMPLES_TARGET} is ${committed === null ? 'missing' : 'stale'} — run \`npm run docs:playground-samples\` and commit the result`);
        process.exit(1);
    }
    if (committed !== samples) writeFileSync(join(root, SAMPLES_TARGET), samples);
    console.error(`build-playground-samples: ${SAMPLES_TARGET} ${committed === samples ? 'unchanged' : 'written'}`);
}
